"""Native pixel binding and pack identities, including the old writer control.

Synthetic old layout: reader header 528 versus real 424 (FAIL); repaired layout:
reader header 512 versus real 512 (PASS). Pixel bytes must also match exactly.
The private source world's 477 packs must have 477 distinct, paired identities.
Fixtures contain generated bytes; absent source files yield exit 3 after them.
"""
from pathlib import Path
import struct
import sys
import unittest

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import convert as c
from formats import Chunk, TrackIndex, chunks, encode_chunks, u32
from merge import DEFAULT_MW, load_index, read_section
from region import pack_hash

ASSETS = all((DEFAULT_MW / name).is_file() for name in ('L2RA.BUN', 'STREAML2RA.BUN'))


def source_pack(offset=0):
    info = bytearray(124)
    struct.pack_into('<I', info, 0, 5)
    row = bytearray(124)
    row[12:16] = b'tex\0'
    struct.pack_into('<I', row, 56, 16)  # pixel size -> target +28
    row[74] = 0x22
    platform = bytes(20) + b'DXT1' + bytes(8)
    header = encode_chunks([Chunk(0x33310001, info), Chunk(0x33310002, bytes(8)),
                            Chunk(0x33310004, row), Chunk(0x33310005, platform)])
    out = c.Builder(offset + 8)
    out.add(0xb3310000, header)
    body = c.Builder(out.position + 8)
    body.add(0x33320001, bytes(24))
    body.add(0x33320002, bytes(range(16)), 128)
    out.add(0xb3320000, body.data)
    return Chunk(0xb3300000, bytes(out.data), offset)


def parts(pack):
    root = chunks(pack.payload, pack.offset + 8)
    h = next(x for x in root if x.kind == 0xb3310000)
    d = next(x for x in root if x.kind == 0xb3320000)
    info = next(x for x in chunks(h.payload, h.offset + 8) if x.kind == 0x33310001)
    return info.payload, d, chunks(d.payload, d.offset + 8)


def reader_header(data):
    # Translate 005605C2..005605D2 literally, independently of the writer.
    first_size = u32(data.payload, 4)
    second_size = u32(data.payload, first_size + 12)
    return data.offset + first_size + second_size + 24


class TexturePackTests(unittest.TestCase):
    def test_reader_and_original_broken_layout(self):
        out, = chunks(c.convert_tpk(source_pack(), 0, c.Stats(pack_section=309)))
        info, data, kids = parts(out)
        self.assertEqual([x.kind for x in kids], [0x33320001, 0, 0x33320002])
        self.assertEqual(reader_header(data), kids[2].offset)
        self.assertEqual((reader_header(data) + 0x87) & ~127, kids[2].offset + 128)
        self.assertEqual(c.aligned_payload(kids[2], 128), bytes(range(16)))
        name = info[32:96].split(b'\0')[0]
        self.assertEqual(u32(info, 96), pack_hash(name.upper()))
        self.assertEqual(u32(info, 96), u32(kids[0].payload, 12))
        # Recreate the original two-child writer at the same absolute position.
        old = c.Builder(data.offset + 8)
        old.add(0x33320001, kids[0].payload)
        old.add(0x33320002, bytes(range(16)), 128)
        broken = Chunk(data.kind, bytes(old.data), data.offset)
        real = chunks(broken.payload, broken.offset + 8)[1].offset
        self.assertNotEqual(reader_header(broken), real)
        print(f'TPK repaired reader/real={reader_header(data)}/{kids[2].offset} PASS; '
              f'old reader/real={reader_header(broken)}/{real} FAIL')

    def test_identity_uses_section_and_source_offset(self):
        hashes = []
        for section, offset in ((100, 0), (100, 128), (101, 0)):
            pack, = chunks(c.convert_tpk(source_pack(offset), 0, c.Stats(pack_section=section)))
            hashes.append(u32(parts(pack)[0], 96))
        self.assertEqual(len(set(hashes)), 3)
        # Moving output bytes must not change the pack's identity.
        moved, = chunks(c.convert_tpk(source_pack(), 128, c.Stats(pack_section=100)), 128)
        self.assertEqual(u32(parts(moved)[0], 96), hashes[0])

    @unittest.skipUnless(ASSETS, 'private source absent')
    def test_world_identities(self):
        index, stream, _ = load_index(DEFAULT_MW, 'L2RA')
        hashes = []
        for section in index.sections:
            roots = chunks(read_section(stream, section))
            if not any(root.kind == 0x80034100 for root in roots):
                if not any(root.kind == 0xb3300000 for root in roots):
                    continue
                from resources import convert_resources
                roots = chunks(convert_resources(roots, section.number)[0])
                converted = True
            else:
                converted = False
            for root in roots:
                if root.kind != 0xb3300000:
                    continue
                pack = root
                if not converted:
                    pack, = chunks(c.convert_tpk(root, 0, c.Stats(pack_section=section.number)))
                info, data, kids = parts(pack)
                self.assertEqual(reader_header(data), kids[2].offset)
                self.assertEqual(u32(info, 96), u32(kids[0].payload, 12))
                hashes.append(u32(info, 96))
        self.assertEqual(len(hashes), 477)
        self.assertEqual(len(set(hashes)), len(hashes))
        print(f'WORLD TPK identities: {len(set(hashes))}/{len(hashes)} distinct')


if __name__ == '__main__':
    result = unittest.main(exit=False).result
    if not result.wasSuccessful():
        raise SystemExit(1)
    if not ASSETS:
        raise SystemExit(3)
